-- NSL Bank schema, reconstructed for PostgreSQL / Supabase.
--
-- The original Oracle DDL (edgar1.cse.lehigh.edu) was never committed to this
-- repository, so every table and column below is inferred from the SQL and
-- result-set reads in scz225zwart/scz225/Database.java. See
-- docs/existing-behavior.md for the evidence behind each choice and the list
-- of inferred details awaiting approval.
--
-- Deliberately NOT included (pending approval, see docs/MIGRATION_TRACKER.md):
--   * NOT NULL / CHECK constraints beyond primary keys - not evidenced in code
--   * Any extra columns (e.g. branch names) - would change the data model

-- ID generation -------------------------------------------------------------
-- The app reads all IDs as strings and relies on the database to generate
-- them (getGeneratedKeys on account_id, card_id, loan_id, transaction_id).
-- The only observed format is 'A00003' for accounts (Database.java:537);
-- the other prefixes follow the same pattern and are inferred.

create sequence customer_id_seq;
create sequence branch_id_seq;
create sequence account_id_seq;
create sequence card_id_seq;
create sequence vendor_id_seq;
create sequence loan_id_seq;
create sequence transaction_id_seq;

-- Customer ------------------------------------------------------------------
create table customer (
    customer_id   text primary key default 'C' || lpad(nextval('customer_id_seq')::text, 5, '0'),
    customer_name text,
    birthday      date,
    address       text
);
alter sequence customer_id_seq owned by customer.customer_id;

-- Branch --------------------------------------------------------------------
-- branch_type 'Full Service' is the only value referenced in code; deposits
-- are only allowed at Full Service branches (App.java:453).
create table branch (
    branch_id   text primary key default 'B' || lpad(nextval('branch_id_seq')::text, 5, '0'),
    branch_type text
);
alter sequence branch_id_seq owned by branch.branch_id;

-- Account and its subtypes (ISA hierarchy) ----------------------------------
create table account (
    account_id    text primary key default 'A' || lpad(nextval('account_id_seq')::text, 5, '0'),
    account_type  text,              -- 'checking' | 'savings' (App.java:637, 649)
    balance       numeric(12, 2),
    interest_rate numeric(5, 2)
);
alter sequence account_id_seq owned by account.account_id;

-- Inserted positionally: INSERT INTO Checking VALUES (?)
create table checking (
    account_id text primary key references account (account_id)
);

-- Inserted positionally: INSERT INTO Savings VALUES (?, ?, ?)
-- Column order must stay (account_id, minimum_balance, penalty).
create table savings (
    account_id      text primary key references account (account_id),
    minimum_balance numeric(12, 2),
    penalty         numeric(12, 2)
);

-- Many-to-many: an account may have several owners (joint accounts).
create table account_ownership (
    account_id  text references account (account_id),
    customer_id text references customer (customer_id),
    primary key (account_id, customer_id)
);

-- Card and its subtypes (ISA hierarchy) -------------------------------------
-- account_id is NULL for credit cards (insertCardTypeCredit omits it).
-- customer_name is a denormalised copy of customer.customer_name.
create table card (
    card_id       text primary key default 'D' || lpad(nextval('card_id_seq')::text, 5, '0'),
    card_type     text,              -- 'credit' | 'debit'
    account_id    text references account (account_id),
    customer_id   text references customer (customer_id),
    customer_name text
);
alter sequence card_id_seq owned by card.card_id;

-- "limit" is a reserved word in PostgreSQL (it was not in Oracle), so the
-- column keeps its original name but must be double-quoted in queries.
create table credit (
    card_id         text primary key references card (card_id),
    interest_rate   numeric(5, 2),
    "limit"         numeric(12, 2),
    running_balance numeric(12, 2),
    balance_due     numeric(12, 2)
);

create table debit (
    card_id text primary key references card (card_id)
);

-- Vendor and Purchase -------------------------------------------------------
create table vendor (
    vendor_id   text primary key default 'V' || lpad(nextval('vendor_id_seq')::text, 5, '0'),
    vendor_name text
);
alter sequence vendor_id_seq owned by vendor.vendor_id;

-- purchase_id is read with getInt (PurchaseRow), so it is numeric.
create table purchase (
    purchase_id   integer generated by default as identity primary key,
    card_id       text references card (card_id),
    vendor_id     text references vendor (vendor_id),
    amount        numeric(12, 2),
    purchase_date timestamp
);

-- Loan ----------------------------------------------------------------------
-- amount is the outstanding balance: payments are applied with
-- UPDATE Loan SET amount = amount - ? (Database.java:130).
create table loan (
    loan_id         text primary key default 'L' || lpad(nextval('loan_id_seq')::text, 5, '0'),
    loan_type       text,            -- stored as typed by the user, e.g. 'mortgage', 'Unsecured'
    amount          numeric(12, 2),
    interest_rate   numeric(5, 2),
    monthly_payment numeric(12, 2),
    customer_id     text references customer (customer_id)
);
alter sequence loan_id_seq owned by loan.loan_id;

-- Transaction ---------------------------------------------------------------
-- Only deposits and withdrawals are recorded here (App.java:501, 570, 591).
create table transaction (
    transaction_id   text primary key default 'T' || lpad(nextval('transaction_id_seq')::text, 5, '0'),
    transaction_type text,           -- 'deposit' | 'withdrawal'
    transaction_date timestamp,
    amount           numeric(12, 2),
    customer_id      text references customer (customer_id),
    account_id       text references account (account_id),
    branch_id        text references branch (branch_id)
);
alter sequence transaction_id_seq owned by transaction.transaction_id;
